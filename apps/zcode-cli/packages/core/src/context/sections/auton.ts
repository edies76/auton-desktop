export function buildAutonSection(): ContextSection {
  return {
    name: "Auton Doctrine",
    source: "auton_doctrine",
    injectionTarget: "system",
    cacheHint: "stable",
    chars: AUTON_DOCTRINE.length,
    tokens: estimateTokens(AUTON_DOCTRINE),
    content: AUTON_DOCTRINE,
    preview: AUTON_DOCTRINE.slice(0, 100),
  };
}
